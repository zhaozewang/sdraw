# Human-readable preamble written to the top of every .sdraw file.
# Kept concise — it sits in the context window of any coding agent that
# reads the file, so every line should earn its place. Regenerated on each
# save, so edits to the stored copy are overwritten by design.
SDRAW_MANUAL = (
    "This is an sdraw board file (JSON). Read before editing.\n"
    "\n"
    "SCHEMA\n"
    "- `schema_version` matches the app's CURRENT_SCHEMA_VERSION. Older "
    "versions are migrated on load; do not roll it back.\n"
    "- `_manual` (this field) is regenerated by the app on every save. "
    "Edits to it are discarded.\n"
    "\n"
    "ELEMENT IDS\n"
    "- `elements[].id` are stable UUIDs. Never regenerate them — sidecar "
    "caches and `renderedCodeHash` are keyed by id.\n"
    "\n"
    "PLOT CODE SHARING\n"
    "- Plot code lives in the top-level `plotCodes` registry keyed by "
    "plotCodeId, NOT in each element.\n"
    "- A plot element references code via `metadata.plotCodeId` and "
    "picks which figure of the returned tuple to render via "
    "`metadata.figureIndex` (0-based).\n"
    "- Two elements with the same plotCodeId share one code string. Edit "
    "`plotCodes[id].code` once; every referencing element sees it.\n"
    "- Legacy `metadata.sourceElementId` is deprecated and auto-migrated "
    "to plotCodeId on open. Do not emit new ones.\n"
    "\n"
    "CACHED OUTPUTS (DO NOT FORGE)\n"
    "- `metadata.lastOutput` (base64 PNG), `.lastStdout`, `.lastError`, "
    "and `.renderedCodeHash` are produced by running the code. The app "
    "owns them.\n"
    "- If you change `plotCodes[X].code`, leave referencing elements' "
    "cached output alone. The app compares `renderedCodeHash` to the "
    "current code hash and marks stale cells with an amber badge; the "
    "user clicks Run on that cell (or Run All) to refresh.\n"
    "- Alternative: clear lastOutput/lastStdout/lastError and drop "
    "renderedCodeHash to force the placeholder state.\n"
    "\n"
    "SIDECAR CACHE\n"
    "- `metadata.plotlyJson` (interactive Plotly spec) is not stored in "
    "this file. It lives at `~/.sdraw/cache/<board.id>/cache.json` and "
    "is regenerated on next run when missing.\n"
    "\n"
    "EDITING TIPS\n"
    "- Preserve element order; the canvas renders in that order.\n"
    "- Keep `updated_at` fresh when you write.\n"
    "- Prefer running sdraw and letting it save — it handles cache "
    "invalidation, hashing, and sidecar cache for you."
)


def _fnv1a(s: str) -> str:
    """FNV-1a 32-bit hash — matches the frontend's fnv1a() exactly."""
    h = 0x811C9DC5
    for ch in s:
        h ^= ord(ch)
        h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) & 0xFFFFFFFF
    return format(h, "08x")


def _with_manual(clean_board: dict) -> dict:
    """Return a new dict with `_manual` injected as the first key, and the
    deprecated top-level `name` field stripped.

    Agents reading the file skim top-down, so ordering matters. Python
    dicts preserve insertion order since 3.7; constructing a fresh dict
    with `_manual` first guarantees the preamble leads the JSON.

    The `name` field is deprecated — the filename stem is the board's
    display name. Every save drops `name` so legacy boards normalize.
    """
    ordered = {"_manual": SDRAW_MANUAL}
    for k, v in clean_board.items():
        if k in ("_manual", "name"):
            continue
        ordered[k] = v
    return ordered


def _code_digest(board: dict) -> str:
    """Same as the frontend codeDigest(): FNV-1a of setup code + sorted
    plot code STRINGS (not keyed by plotCodeId).

    Migration invariance: the v2→v3 migration assigns random UUIDs to new
    registry entries, so hashing by plotCodeId would be nondeterministic
    (two consecutive /digest calls on an unmigrated file would return
    different hashes → spurious external-conflict prompts). Sorting by
    content collapses that randomness.
    """
    parts = []
    setup_code = (board.get("setup") or {}).get("code", "")
    parts.append(f"setup\n{setup_code}")
    plot_codes = board.get("plotCodes") or {}
    codes = sorted(str(entry.get("code", "")) for entry in plot_codes.values())
    for code in codes:
        parts.append(f"plot\n{code}")
    return _fnv1a("\n---\n".join(parts))


class CreateBoardRequest(BaseModel):
    name: str = "Untitled Board"


@router.get("/")
async def list_boards(request: Request):
    """Return summary list of all boards."""
    ws_service = request.app.state.workspace
    return ws_service.list_boards()


@router.post("/", status_code=201)
async def create_board(body: CreateBoardRequest, request: Request):
    """Create a new board with a generated UUID."""
    ws_service = request.app.state.workspace
    board = Board(name=body.name)
    saved = ws_service.save_board(board)
    return saved.model_dump()


@router.get("/{board_id}")
async def get_board(board_id: str, request: Request):
    """Get a single board by ID."""
    ws_service = request.app.state.workspace
    board = ws_service.load_board(board_id)
    if board is None:
        raise HTTPException(status_code=404, detail="Board not found")
    return board.model_dump()


@router.put("/{board_id}")
async def update_board(board_id: str, board: Board, request: Request):
    """Update an existing board (full replacement)."""
    ws_service = request.app.state.workspace
    existing = ws_service.load_board(board_id)
    if existing is None:
        raise HTTPException(status_code=404, detail="Board not found")
    board.id = board_id  # Ensure ID consistency
    saved = ws_service.save_board(board)
    return saved.model_dump()


@router.delete("/{board_id}")
async def delete_board(board_id: str, request: Request):
    """Delete a board by ID."""
    ws_service = request.app.state.workspace
    deleted = ws_service.delete_board(board_id)
    if not deleted:
        raise HTTPException(status_code=404, detail="Board not found")
    return {"detail": "Board deleted", "id": board_id}


# ---- File-path-based operations (used by the frontend) ----

class SaveBoardToFileRequest(BaseModel):
    board: dict
    path: str


@router.post("/save")
async def save_board_to_file(body: SaveBoardToFileRequest):
    """Save a board to .sdraw file + centralized cache.

    .sdraw file (git-friendly, self-contained): code, cropped PNGs, embedded
    images, crop rects, camera state, layout, thumbnail.

    Cache (~/.sdraw/cache/<board-id>/): plotlyJson — the interactive Plotly
    spec stays local-only by design so .sdraw files round-trip cleanly
    between devices without carrying huge JSON blobs.

    Returns a `size` field (bytes written) and `oversized: True` when the
    file crosses SDRAW_SOFT_SIZE_LIMIT so the frontend can warn the user.
    """
    from services.board_cache import save_cache, strip_cached_fields

    # Soft cap used to warn the user that their .sdraw is getting heavy.
    # Not an error — saving still succeeds. Matches the frontend render
    # guarantee: we always write whatever bytes we're given.
    SDRAW_SOFT_SIZE_LIMIT = 250 * 1024 * 1024  # 250 MB

    try:
        p = Path(body.path).resolve()
        p.parent.mkdir(parents=True, exist_ok=True)

        # Write cache (plotlyJson only — thumbnail now lives in .sdraw)
        save_cache(body.board)

        # Write clean .sdraw file (without cached fields). Inject the
        # _manual preamble at the top so any coding agent opening the
        # file has the invariants in its context window.
        clean_board = _with_manual(strip_cached_fields(body.board))
        payload = json.dumps(clean_board, indent=2)
        p.write_text(payload)
        size = len(payload.encode("utf-8"))
        mtime = p.stat().st_mtime

        # Clean up legacy .blobs companion file if it exists
        legacy_blobs = p.parent / (p.name + ".blobs")
        if legacy_blobs.exists():
            try:
                legacy_blobs.unlink()
            except OSError:
                pass

        # Do NOT echo the board back — the frontend already has it and
        # shipping a ~10 MB response on every autosave is what made save
        # feel blocking over slow links. Callers that genuinely need the
        # post-save board shape can migrate locally.
        return {
            "path": str(p),
            "size": size,
            "mtime": mtime,
            "oversized": size > SDRAW_SOFT_SIZE_LIMIT,
            "soft_limit": SDRAW_SOFT_SIZE_LIMIT,
        }
    except OSError as exc:
        raise HTTPException(status_code=400, detail=str(exc))


class SaveDeltaRequest(BaseModel):
    path: str
    board_id: str
    updated_at: str
    thumbnail: str | None = None
    # Elements that changed — sent as full element dicts, merged by id
    dirty_elements: list[dict] = []
    # Element ids that were removed
    removed_ids: list[str] = []
    # Board-level fields — only sent when they changed
    setup: dict | None = None
    plot_codes: dict | None = None
    canvas: dict | None = None
    auto_export: dict | None = None


@router.post("/save-delta")
async def save_board_delta(body: SaveDeltaRequest):
    """Apply a partial update to an existing .sdraw file.

    Instead of receiving the entire board (often 10+ MB), the client
    sends only the elements that actually changed plus any modified
    board-level fields. The backend reads the file, merges the delta,
    and writes back. This reduces save network traffic from ~12 MB to
    ~100 KB for the common case (one plot output changed).

    Falls through to 409 if the file doesn't exist (client should use
    the full /save endpoint for first writes).
    """
    from services.board_cache import save_cache, strip_cached_fields

    p = Path(body.path).resolve()
    if not p.exists():
        raise HTTPException(status_code=409, detail="File not found; use full save")

    try:
        existing = json.loads(p.read_text())
    except (json.JSONDecodeError, OSError) as exc:
        raise HTTPException(status_code=400, detail=f"Cannot read board file: {exc}")

    # Verify board id matches to prevent accidental cross-board writes
    if existing.get("id") != body.board_id:
        raise HTTPException(status_code=409, detail="Board id mismatch; use full save")

    # Merge elements: index existing by id, apply updates/adds/removes
    el_map: dict[str, dict] = {e["id"]: e for e in existing.get("elements", []) if "id" in e}
    for el in body.dirty_elements:
        el_map[el["id"]] = el
    for rid in body.removed_ids:
        el_map.pop(rid, None)
    # Preserve original element order where possible, appending new ones
    old_ids = [e["id"] for e in existing.get("elements", []) if "id" in e]
    ordered = []
    seen = set()
    for eid in old_ids:
        if eid in el_map and eid not in seen:
            ordered.append(el_map[eid])
            seen.add(eid)
    for eid, el in el_map.items():
        if eid not in seen:
            ordered.append(el)
    existing["elements"] = ordered

    # Merge board-level fields
    if body.setup is not None:
        existing["setup"] = body.setup
    if body.plot_codes is not None:
        existing["plotCodes"] = body.plot_codes
    if body.canvas is not None:
        existing["canvas"] = body.canvas
    if body.auto_export is not None:
        existing["autoExport"] = body.auto_export
    if body.thumbnail is not None:
        existing["thumbnail"] = body.thumbnail
    existing["updated_at"] = body.updated_at

    # Write cache — only the dirty elements have authoritative metadata
    # (the frontend just ran/saved them). Unchanged siblings keep whatever
    # the sidecar had, so lazy-fetched plotlyJson isn't wiped by an
    # unrelated canvas edit.
    authoritative_ids = {
        el["id"] for el in body.dirty_elements if isinstance(el.get("id"), str)
    }
    save_cache(existing, authoritative_ids=authoritative_ids)

    # Write clean file with the _manual preamble re-injected at the top.
    # Even if the existing file already has one, we regenerate it so the
    # wording stays current as invariants evolve.
    clean = _with_manual(strip_cached_fields(existing))
    payload = json.dumps(clean, indent=2)
    p.write_text(payload)
    size = len(payload.encode("utf-8"))
    mtime = p.stat().st_mtime

    return {"path": str(p), "size": size, "mtime": mtime}


class OpenBoardFromFileRequest(BaseModel):
    path: str


@router.post("/open")
async def open_board_from_file(body: OpenBoardFromFileRequest):
    """Load a board from .sdraw file, merging cached data if available."""
    from services.board_cache import merge_cache_into_board, migrate_board_schema

    p = Path(body.path).resolve()
    if not p.exists() or not p.is_file():
        raise HTTPException(status_code=404, detail="Board file not found")
    try:
        mtime = p.stat().st_mtime
        data = json.loads(p.read_text())
        # _manual is a file-only preamble for coding agents — it's not
        # part of the runtime Board shape. Drop it before handing the
        # board to the frontend so Board type stays clean.
        data.pop("_manual", None)
        # Upgrade older schema versions in-memory (next save persists it)
        data = migrate_board_schema(data)
        # Merge cached data (plotlyJson, thumbnail) from ~/.sdraw/cache/
        data = merge_cache_into_board(data)
        return {"path": str(p), "board": data, "mtime": mtime}
    except (json.JSONDecodeError, OSError) as exc:
        raise HTTPException(status_code=400, detail=str(exc))


