class RenameBoardFileRequest(BaseModel):
    old_path: str
    new_path: str


@router.post("/rename-file")
async def rename_board_file(body: RenameBoardFileRequest):
    """Rename a .sdraw file on disk. Also moves the matching crash-recovery
    checkpoint (`.<name>.checkpoint`) so recovery still works for the new
    filename. Refuses to overwrite an existing target and refuses
    cross-directory moves (that's a separate "move" operation).
    """
    old_p = Path(body.old_path).resolve()
    new_p = Path(body.new_path).resolve()
    if not old_p.exists() or not old_p.is_file():
        raise HTTPException(status_code=404, detail="Source file not found")
    if old_p == new_p:
        return {"path": str(old_p), "mtime": old_p.stat().st_mtime}
    if new_p.exists():
        raise HTTPException(status_code=409, detail="Target file already exists")
    if new_p.parent != old_p.parent:
        raise HTTPException(status_code=400, detail="Cross-directory rename not supported")
    try:
        old_p.rename(new_p)
        old_cp = old_p.parent / f".{old_p.name}.checkpoint"
        if old_cp.exists():
            new_cp = new_p.parent / f".{new_p.name}.checkpoint"
            try:
                old_cp.rename(new_cp)
            except OSError:
                pass
        return {"path": str(new_p), "mtime": new_p.stat().st_mtime}
    except OSError as exc:
        raise HTTPException(status_code=400, detail=str(exc))


# ---- Checkpoint / crash-recovery ----

def _checkpoint_path(board_path: str) -> Path:
    """Return the hidden checkpoint file path for a given board file."""
    p = Path(board_path).resolve()
    return p.parent / f".{p.name}.checkpoint"


class CheckpointRequest(BaseModel):
    board: dict
    path: str  # path to the main board file


@router.post("/checkpoint/save")
async def save_checkpoint(body: CheckpointRequest):
    """Save a checkpoint (hidden file) for crash recovery. Includes full blob data."""
    cp = _checkpoint_path(body.path)
    try:
        cp.write_text(json.dumps(body.board))
        return {"path": str(cp)}
    except OSError as exc:
        raise HTTPException(status_code=400, detail=str(exc))


class CheckpointCheckRequest(BaseModel):
    path: str  # path to the main board file


@router.post("/checkpoint/check")
async def check_checkpoint(body: CheckpointCheckRequest):
    """Check if a checkpoint exists and is newer than the saved board file."""
    cp = _checkpoint_path(body.path)
    board_p = Path(body.path).resolve()
    if not cp.exists():
        return {"exists": False}
    try:
        cp_mtime = cp.stat().st_mtime
        board_mtime = board_p.stat().st_mtime if board_p.exists() else 0
        return {
            "exists": True,
            "newer": cp_mtime > board_mtime,
            "checkpoint_modified": cp_mtime,
            "board_modified": board_mtime,
        }
    except OSError:
        return {"exists": False}


@router.post("/checkpoint/load")
async def load_checkpoint(body: CheckpointCheckRequest):
    """Load board data from a checkpoint file."""
    cp = _checkpoint_path(body.path)
    if not cp.exists():
        raise HTTPException(status_code=404, detail="No checkpoint found")
    try:
        data = json.loads(cp.read_text())
        return {"path": body.path, "board": data}
    except (json.JSONDecodeError, OSError) as exc:
        raise HTTPException(status_code=400, detail=str(exc))


@router.post("/checkpoint/delete")
async def delete_checkpoint(body: CheckpointCheckRequest):
    """Delete a checkpoint file."""
    cp = _checkpoint_path(body.path)
    if cp.exists():
        cp.unlink()
    return {"deleted": True}


class DigestRequest(BaseModel):
    path: str


@router.post("/digest")
async def board_code_digest(body: DigestRequest):
    """Return the code digest + mtime for a board file on disk.

    The digest (FNV-1a over setup code + sorted plot code strings) is the
    legacy external-change signal; the frontend now primarily trusts
    ``mtime``, which is cheap, deterministic, and impossible to false-fire
    on schema-migration randomness. Digest is kept as a secondary guard
    for the (unusual) case where mtime bumped but content is genuinely
    identical.
    """
    from services.board_cache import migrate_board_schema

    p = Path(body.path).resolve()
    if not p.exists() or not p.is_file():
        raise HTTPException(status_code=404, detail="Board file not found")
    try:
        mtime = p.stat().st_mtime
        data = json.loads(p.read_text())
        data = migrate_board_schema(data)
        return {"digest": _code_digest(data), "mtime": mtime}
    except (json.JSONDecodeError, OSError) as exc:
        raise HTTPException(status_code=400, detail=str(exc))
